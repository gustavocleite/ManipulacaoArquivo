    private void jButton_SalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_SalvarActionPerformed
        try {

            Endereco endereco = new Endereco(
                    jTextField_Rua.getText(),
                    Integer.parseInt(jTextField_Numero.getText()),
                    jTextField_Bairro.getText(),
                    jTextField_Cidade.getText(),
                    jTextField_UF.getText()
            );

            Cliente cliente = new Cliente(
                    jTextField_Nome.getText(),
                    jTextField_Telefone.getText(),
                    endereco
            );

            clienteDAO.salvar(cliente);

            JOptionPane.showMessageDialog(
                    this,
                    "Cliente cadastrado com sucesso!"
            );

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "O número do endereço deve ser um número inteiro.",
                    "Dados inválidos",
                    JOptionPane.WARNING_MESSAGE
            );

        } catch (IOException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Erro ao salvar os dados no arquivo.",
                    "Erro",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_jButton_SalvarActionPerformed

